import type { MessageDefinition } from './types';

const k = (
  key: string,
  register: string,
  text: string,
  http: number,
  refs: readonly string[],
  placeholders?: readonly string[],
) =>
  ({
    key,
    register,
    // The register writes placeholders as <n>.
    srsText: text.replace(/\{(\w+)\}/g, '<$1>'),
    class: 'K',
    type: 'error',
    http,
    en: text,
    ...(placeholders ? { placeholders } : {}),
    approval: 'register',
    batch: 2,
    refs,
  }) as const;

const r = (
  key: string,
  register: string,
  srsText: string,
  http: number,
  en: string,
  refs: readonly string[],
  placeholders?: readonly string[],
) =>
  ({
    key,
    register,
    srsText,
    class: 'R',
    type: 'error',
    http,
    en,
    ...(placeholders ? { placeholders } : {}),
    approval: 'approved',
    batch: 2,
    refs: [...refs, 'client standing approval 2026-10-03'],
  }) as const;

const n = (
  key: string,
  http: number,
  en: string,
  refs: readonly string[],
  placeholders?: readonly string[],
) =>
  ({
    key,
    register: null,
    srsText: null,
    class: 'N',
    type: 'error',
    http,
    en,
    ...(placeholders ? { placeholders } : {}),
    approval: 'approved',
    batch: 2,
    refs: [...refs, 'client standing approval 2026-10-03'],
  }) as const;

