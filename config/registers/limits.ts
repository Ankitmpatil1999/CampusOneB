/**
 * Limits and configuration register (docs/01 §5; SRS v2.1 27.4; ADR-0008).
 *
 * `basis`:
 * - `register` — the 27.4 value, unchanged;
 * - `adopted`  — an open item's proposed resolution (07a disposition A/R) or a change request;
 * - `proposed` — a limits-register change awaiting approval (Q21 (c)). None left: the client approved
 *   every proposed limit on 2026-10-02 (Q13, Q21), so they are now `adopted`.
 * Every value is configuration (NFR-52); `scope` says where it may be overridden
 * (P platform · I institution · L plan).
 */
export type LimitBasis = 'register' | 'adopted' | 'proposed';
export type LimitScope = 'P' | 'P/I' | 'I' | 'L' | 'P/L';

export interface LimitDefinition<T = number> {
  readonly key: string;
  readonly value: T;
  readonly unit: string;
  readonly scope: LimitScope;
  readonly basis: LimitBasis;
  /** The 27.4 value as built, when it differs from `value`. */
  readonly srsValue?: string;
  /**
   * Operators may change the value within this range (platform settings, client 2026-10-02: "give
   * us the provision to change"). Values without a range are fixed until a range is agreed.
   */
  readonly adjustable?: { readonly min: number; readonly max: number };
  readonly refs: readonly string[];
}

const def = <T>(d: LimitDefinition<T>): LimitDefinition<T> => d;

