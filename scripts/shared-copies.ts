/**
 * Keeps the files shared by the three projects identical (RNG-GOV-005: one rule, not three copies
 * that drift). Each shared file has one master; the other projects hold byte-identical copies, the
 * way the reference projects each keep their own utils/money and format files.
 *
 *   npm run shared:check   fails if a copy differs from its master or messages.en.ts is stale
 *   npm run shared:sync    regenerates messages.en.ts from the registers and rewrites every copy
 *
 * A sibling project that is not checked out is reported and skipped.
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import * as prettier from 'prettier';
import { englishBundle } from '../config/registers';

const BACKEND = join(import.meta.dirname, '..');
const REPO = join(BACKEND, '..');
const WEB = join(REPO, 'CampusOne_Web_App');
const MOBILE = join(REPO, 'CampusOne_Mobile_App');

interface Location {
  readonly project: string;
  readonly path: string;
}
interface SharedFile {
  readonly master: Location;
  readonly copies: readonly Location[];
  /** Generated masters are rebuilt from the registers before copying. */
  readonly generate?: () => Promise<string>;
}

const at = (project: string, ...path: string[]): Location => ({
  project,
  path: join(project, ...path),
});
const utilsCopies = (f: string) => [
  at(WEB, 'src', 'components', 'Utils', f),
  at(MOBILE, 'src', 'utils', f),
];

const SHARED: readonly SharedFile[] = [
  ...['money.ts', 'format.ts', 'translate.ts'].map((f) => ({
    master: at(BACKEND, 'utils', f),
    copies: utilsCopies(f),
  })),
  {
    master: at(BACKEND, 'utils', 'validators', 'patterns.ts'),
    copies: utilsCopies('patterns.ts'),
  },
  {
    master: at(BACKEND, 'utils', 'messages.en.ts'),
    copies: utilsCopies('messages.en.ts'),
    generate: renderMessages,
  },
  {
    master: at(WEB, 'src', 'theme', 'tokens.ts'),
    copies: [at(MOBILE, 'src', 'theme', 'tokens.ts')],
  },
];

async function renderMessages(): Promise<string> {
  const bundle = englishBundle();
  const sorted = Object.fromEntries(
    Object.keys(bundle)
      .sort()
      .map((k) => [k, bundle[k]]),
  );
  const source = [
    '// Shared file, generated by `npm run shared:sync` in CampusOne_Backend_API from config/registers',
    '// (messages and status labels). Do not edit; copies live in the web and mobile apps.',
    `export const MESSAGES_EN: Readonly<Record<string, string>> = ${JSON.stringify(sorted)};`,
    '',
  ].join('\n');
  const options = (await prettier.resolveConfig(join(BACKEND, 'utils', 'messages.en.ts'))) ?? {};
  return prettier.format(source, { ...options, parser: 'typescript' });
}

const write = process.argv.includes('--write');
const show = (p: string) => relative(REPO, p).split('\\').join('/');
const checkedOut = (l: Location) => existsSync(join(l.project, 'package.json'));
const problems: string[] = [];

for (const file of SHARED) {
  if (!checkedOut(file.master)) {
    console.log(`skip ${show(file.master.path)} (project not checked out)`);
    continue;
  }
  let master = existsSync(file.master.path) ? readFileSync(file.master.path, 'utf8') : '';
  if (file.generate) {
    const fresh = await file.generate();
    if (fresh !== master) {
      if (write) {
        writeFileSync(file.master.path, fresh);
        console.log(`generated ${show(file.master.path)}`);
      } else problems.push(`${show(file.master.path)} is stale`);
      master = fresh;
    }
  }
  for (const copy of file.copies) {
    if (!checkedOut(copy)) {
      console.log(`skip ${show(copy.path)} (project not checked out)`);
      continue;
    }
    const current = existsSync(copy.path) ? readFileSync(copy.path, 'utf8') : null;
    if (current === master) continue;
    if (write) {
      writeFileSync(copy.path, master);
      console.log(`copied ${show(file.master.path)} -> ${show(copy.path)}`);
    } else problems.push(`${show(copy.path)} differs from ${show(file.master.path)}`);
  }
}

if (problems.length > 0) {
  console.error(
    `Shared files out of step (run \`npm run shared:sync\`):\n  ${problems.join('\n  ')}`,
  );
  process.exit(1);
}
console.log(write ? 'shared files synced' : 'shared files identical');
